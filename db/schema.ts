import { sql } from "drizzle-orm";
import { index, integer, sqliteTable, text, uniqueIndex } from "drizzle-orm/sqlite-core";

export const games = sqliteTable("games", {
  id: text("id").primaryKey(),
  title: text("title").notNull(),
  settingsJson: text("settings_json").notNull().default("{}"),
  accessCode: text("access_code").notNull(),
  registrationInviteHash: text("registration_invite_hash"),
  journalistPreset: text("journalist_preset").notNull().default("christie"),
  journalistDetailMode: text("journalist_detail_mode").notNull().default("adapt"),
  journalistNotes: text("journalist_notes").notNull().default(""),
  journalistModel: text("journalist_model").notNull().default(""),
  journalistEffort: text("journalist_effort").notNull().default("default"),
  journalistCorePrompt: text("journalist_core_prompt").notNull().default(""),
  journalistSourcePrompt: text("journalist_source_prompt").notNull().default(""),
  journalistRolePrompt: text("journalist_role_prompt").notNull().default(""),
  journalistPresetsJson: text("journalist_presets_json").notNull().default(""),
  journalistDetailModesJson: text("journalist_detail_modes_json").notNull().default(""),
  journalistFormatsJson: text("journalist_formats_json").notNull().default(""),
  crewRolesJson: text("crew_roles_json").notNull().default(""),
  fogMode: text("fog_mode", { enum: ["auto", "on", "off"] }).notNull().default("auto"),
  exposureRule: text("exposure_rule", { enum: ["eliminate_killer", "cancel_kill"] }).notNull().default("eliminate_killer"),
  status: text("status", { enum: ["draft", "running", "paused", "finished"] }).notNull().default("draft"),
  startedAt: text("started_at"),
  endedAt: text("ended_at"),
  winnerId: text("winner_id"),
  winnerIdsJson: text("winner_ids_json").notNull().default("[]"),
  revision: integer("revision").notNull().default(0),
  createdAt: text("created_at").notNull().default(sql`CURRENT_TIMESTAMP`),
});

export const players = sqliteTable(
  "players",
  {
    id: text("id").primaryKey(),
    gameId: text("game_id").notNull(),
    name: text("name").notNull(),
    group_name: text("group_name").notNull().default(""),
    roleKey: text("role_key").notNull().default(""),
    customRole: text("custom_role").notNull().default(""),
    feminine: integer("feminine").notNull().default(0),
    profileCompleted: integer("profile_completed").notNull().default(0),
    secretHash: text("secret_hash").notNull(),
    pinHash: text("pin_hash"),
    pinSalt: text("pin_salt"),
    pinFailedAttempts: integer("pin_failed_attempts").notNull().default(0),
    pinLockedUntil: text("pin_locked_until"),
    authVersion: integer("auth_version").notNull().default(0),
    photoKey: text("photo_key"),
    photoType: text("photo_type"),
    status: text("status", { enum: ["active", "eliminated", "removed"] }).notNull().default("active"),
    targetId: text("target_id"),
    eliminatedAt: text("eliminated_at"),
    eliminationReason: text("elimination_reason", { enum: ["killed", "exposed"] }),
    removedAt: text("removed_at"),
    createdAt: text("created_at").notNull().default(sql`CURRENT_TIMESTAMP`),
  },
  (table) => [
    uniqueIndex("idx_players_secret_hash").on(table.secretHash),
    index("idx_players_game_status").on(table.gameId, table.status),
    index("idx_players_target").on(table.gameId, table.targetId),
  ],
);

export const events = sqliteTable(
  "events",
  {
    id: text("id").primaryKey(),
    gameId: text("game_id").notNull(),
    revision: integer("revision").notNull(),
    eliminatedPlayerId: text("eliminated_player_id").notNull(),
    predecessorId: text("predecessor_id").notNull(),
    inheritedTargetId: text("inherited_target_id").notNull(),
    type: text("type", { enum: ["killed", "exposed"] }).notNull(),
    epitaph: text("epitaph").notNull(),
    publishAt: text("publish_at"),
    approvalRequired: integer("approval_required").notNull().default(0),
    approvedAt: text("approved_at"),
    articleFormat: text("article_format"),
    articleSection: text("article_section"),
    articleHeadline: text("article_headline"),
    articleBody: text("article_body"),
    articleQuote: text("article_quote"),
    pressDetails: text("press_details"),
    pressFinalWords: text("press_final_words"),
    pressSubmittedAt: text("press_submitted_at"),
    articleGeneratedAt: text("article_generated_at"),
    articleStatus: text("article_status", { enum: ["ready", "pending", "failed"] }).notNull().default("ready"),
    articleManual: integer("article_manual").notNull().default(0),
    articleSuppressed: integer("article_suppressed").notNull().default(0),
    createdAt: text("created_at").notNull().default(sql`CURRENT_TIMESTAMP`),
    undoneAt: text("undone_at"),
  },
  (table) => [
    uniqueIndex("idx_events_game_revision").on(table.gameId, table.revision),
    index("idx_events_game_created").on(table.gameId, table.createdAt),
    index("idx_events_game_publish").on(table.gameId, table.publishAt),
  ],
);

export const articleGenerations = sqliteTable(
  "article_generations",
  {
    id: text("id").primaryKey(),
    gameId: text("game_id").notNull(),
    eventId: text("event_id").notNull(),
    model: text("model").notNull(),
    effort: text("effort").notNull(),
    requestJson: text("request_json").notNull(),
    responseBody: text("response_body").notNull().default(""),
    outputText: text("output_text").notNull().default(""),
    parsedArticleJson: text("parsed_article_json").notNull().default(""),
    httpStatus: integer("http_status"),
    openaiRequestId: text("openai_request_id").notNull().default(""),
    responseId: text("response_id").notNull().default(""),
    outcome: text("outcome", { enum: ["ai", "fallback"] }).notNull(),
    fallbackReason: text("fallback_reason"),
    errorMessage: text("error_message"),
    createdAt: text("created_at").notNull().default(sql`CURRENT_TIMESTAMP`),
  },
  (table) => [
    index("idx_article_generations_event_created").on(table.eventId, table.createdAt),
    index("idx_article_generations_game_created").on(table.gameId, table.createdAt),
  ],
);

export const gameMutations = sqliteTable("game_mutations", {
  gameId: text("game_id").notNull(),
  revision: integer("revision").notNull(),
}, (table) => [uniqueIndex("idx_game_mutations_revision").on(table.gameId, table.revision)]);
